// Writes THIRD-PARTY-NOTICES.md from what actually reaches a user (T1.10.6).
//
// `license-checker` cannot read Bun's isolated store, so this walks it directly. It starts from
// what the app itself uses and follows each package's own `dependencies`, so build-time tooling
// — linters, the bundler, test runners — is excluded rather than filtered out by name.
//
// AMC's app dependencies are declared as devDependencies on purpose: electron-builder ships
// `out/**` only, and everything the app needs is bundled into it. So for this purpose the
// desktop package's devDependencies are runtime, minus the toolchain listed below.
//
// Run: `node scripts/third-party-notices.mjs`
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const STORE = join(ROOT, 'node_modules', '.bun');

/** Used to build and check the app, never shipped inside it. */
const TOOLCHAIN = new Set([
  '@playwright/test',
  '@tailwindcss/vite',
  '@types/react',
  '@types/react-dom',
  '@vitejs/plugin-react',
  'electron-builder',
  'electron-vite',
  'vite',
  'tailwindcss',
]);

/** Every package.json in the store, keyed by name, newest-installed copy wins ties. */
function readStore() {
  const byName = new Map();
  for (const entry of readdirSync(STORE, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const inner = join(STORE, entry.name, 'node_modules');
    if (!existsSync(inner)) continue;
    for (const top of readdirSync(inner, { withFileTypes: true })) {
      const rels = top.name.startsWith('@')
        ? readdirSync(join(inner, top.name), { withFileTypes: true }).map(
            (d) => `${top.name}/${d.name}`,
          )
        : [top.name];
      for (const rel of rels) {
        const dir = join(inner, rel);
        const manifest = join(dir, 'package.json');
        if (!existsSync(manifest) || byName.has(rel)) continue;
        try {
          const pkg = JSON.parse(readFileSync(manifest, 'utf8'));
          if (!pkg.name) continue;
          byName.set(pkg.name, {
            name: pkg.name,
            version: pkg.version ?? '',
            license:
              typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'UNKNOWN'),
            url:
              typeof pkg.repository === 'string'
                ? pkg.repository
                : (pkg.repository?.url?.replace(/^git\+/, '').replace(/\.git$/, '') ??
                  pkg.homepage ??
                  ''),
            deps: Object.keys(pkg.dependencies ?? {}),
          });
        } catch {
          // A manifest we cannot read is not one we can credit.
        }
      }
    }
  }
  return byName;
}

const workspace = (rel) => JSON.parse(readFileSync(join(ROOT, rel, 'package.json'), 'utf8'));
const store = readStore();

// Seeds: what the app and its packages declare, minus the toolchain, minus our own workspaces.
const seeds = new Set();
for (const [rel, keys] of [
  ['packages/core', ['dependencies']],
  ['packages/adapters/claude-code', ['dependencies']],
  ['packages/adapters/codex-cli', ['dependencies']],
  ['apps/desktop', ['dependencies', 'devDependencies']],
]) {
  const pkg = workspace(rel);
  for (const key of keys) {
    for (const name of Object.keys(pkg[key] ?? {})) {
      if (name.startsWith('@amc/') || TOOLCHAIN.has(name)) continue;
      seeds.add(name);
    }
  }
}

// Everything those pull in at runtime.
const shipped = new Map();
const queue = [...seeds];
while (queue.length) {
  const name = queue.pop();
  if (shipped.has(name)) continue;
  const pkg = store.get(name);
  if (!pkg) continue;
  shipped.set(name, pkg);
  queue.push(...pkg.deps);
}

const list = [...shipped.values()].sort((a, b) => (a.name < b.name ? -1 : 1));
const byLicense = new Map();
for (const pkg of list) byLicense.set(pkg.license, (byLicense.get(pkg.license) ?? 0) + 1);

const lines = [
  '# Third-party notices',
  '',
  'Agent Management Commander is built on the packages below, each of which remains under its',
  'own license. Electron, and through it Chromium and Node.js, carry their own notices inside',
  'the installed application.',
  '',
  'Generated by `node scripts/third-party-notices.mjs` from the installed dependency tree.',
  '',
  '## Licenses in use',
  '',
  ...[...byLicense.entries()]
    .sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
    .map(([license, count]) => `- ${license} — ${count} package${count === 1 ? '' : 's'}`),
  '',
  '## Packages',
  '',
  '| Package | Version | License |',
  '| ------- | ------- | ------- |',
  ...list.map(
    (p) => `| ${p.url ? `[${p.name}](${p.url})` : p.name} | ${p.version} | ${p.license} |`,
  ),
  '',
];

writeFileSync(join(ROOT, 'THIRD-PARTY-NOTICES.md'), lines.join('\n'));
process.stdout.write(`wrote THIRD-PARTY-NOTICES.md for ${list.length} packages\n`);

const unknown = list.filter((p) => p.license === 'UNKNOWN');
if (unknown.length)
  process.stdout.write(`no license field: ${unknown.map((p) => p.name).join(', ')}\n`);
